import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const read=path=>readFileSync(path,'utf8')
const migration=read('supabase/migrations/20261001222000_school_calendar_year_successor.sql')
const calendar=read('src/app/dashboard/calendar/page.tsx')
const refresh=read('src/app/api/calendar/official-source/route.ts')
const cron=read('src/app/api/cron/official-calendar-sources/route.ts')
const holidays=read('src/lib/haiti-holidays.ts')
const suggestions=read('src/components/haiti-holiday-suggestions.tsx')
const sqlCheck=read('supabase/ci/school-calendar-verification.sql')
const migrationWorkflow=read('.github/workflows/supabase-migration-check.yml')

assert.match(migration,/create_academic_year_with_successor/,'year setup exposes the successor-aware RPC')
assert.match(migration,/successor_start:=p_end_date/,'successor starts on the configured current-year end date')
assert.match(migration,/successor_start\+span_days/,'successor date range is derived from the first year length')
assert.match(migration,/start_date>=successor_start/,'do not create another successor when a later year exists')
assert.match(migration,/private\.has_role\(sid,array\['school_admin','director'\]\)/,'only director and school administrator can adjust year dates')
for(const component of ['AcademicYearCalendar','AttendanceCalendar','HaitiHolidaySuggestions','ExamCalendar'])assert.ok(calendar.includes(component),`${component} is present in the unified school calendar`)
assert.match(refresh,/auth\.getUser\(\)/,'online source refresh requires an authenticated user')
assert.match(refresh,/school_admin','director','secretary','surveillant','censeur/,'online source refresh is restricted to authorized staff')
assert.match(refresh,/menfp\.gouv\.ht/,'refresh checks the MENFP source')
assert.match(refresh,/OFFICIAL_CALENDAR_PAGES/,'manual refresh tries official backup pages as well as MENFP')
assert.match(refresh,/sources_reachable/,'manual refresh reports partial availability instead of failing on one unavailable source')
assert.match(cron,/timingSafeEqual/,'scheduled source check authenticates using a constant-time secret comparison')
assert.match(cron,/SUPABASE_SERVICE_ROLE_KEY\|\|process\.env\.SUPABASE_SECRET_KEY/,'scheduled discovery requires a private Supabase key')
assert.match(cron,/OFFICIAL_CALENDAR_PAGES/,'scheduled discovery checks official ministry and government pages')
const sourceParser=read('src/lib/official-calendar-sources.ts')
assert.match(sourceParser,/communication\.gouv\.ht\/institution\/education/,'source list includes the Government education archive')
assert.match(sourceParser,/communication\.gouv\.ht\/ds\/circulaire/,'source list includes government circular archive')
assert.match(sourceParser,/communication\.gouv\.ht\/communiques/,'source list includes government communiqué archive')
assert.match(sourceParser,/OFFICIAL_CALENDAR_HOSTS/,'calendar links are restricted to official government hosts')
assert.match(sourceParser,/20\\d\{2\}/,'calendar links can be labeled with school-year dates')
assert.match(cron,/official_calendar_sources/,'scheduled discovery persists source links for staff review')
assert.doesNotMatch(cron,/school_closures/,'scheduled discovery must not activate school closures')
const vercel=JSON.parse(read('vercel.json'))
assert.ok(vercel.crons.some(job=>job.path==='/api/cron/official-calendar-sources'&&job.schedule==='15 11 * * *'),'Vercel checks official calendar sources daily')
assert.match(suggestions,/Refresh online suggestions/,'the calendar exposes online source refresh')
assert.match(suggestions,/Official calendars detected automatically/,'the calendar displays sources discovered by the daily check')
assert.match(suggestions,/approve closures individually/,'official source dates remain subject to staff review')
assert.match(holidays,/fixed\(year,9,20,'Dessalines Day'\)/,'include Dessalines Day')
assert.match(holidays,/fixed\(year,10,17,'Dessalines Commemoration'\)/,'include Dessalines commemoration')
assert.match(holidays,/fixed\(year,1,2,'Ancestors’ Day'\)/,'include Ancestors Day')
assert.match(sqlCheck,/rollback;\s*$/,'calendar database integration fixture is rollback-only')
assert.match(sqlCheck,/successor does not begin at configured end date/,'database fixture verifies successor start date')
assert.match(sqlCheck,/staff could not review and activate the successor year/,'database fixture verifies staff review and activation')
assert.match(migrationWorkflow,/20261001222000_school_calendar_year_successor\.sql/,'migration is included in isolated Supabase CI')
assert.match(migrationWorkflow,/school-calendar-verification\.sql/,'isolated Supabase CI executes the calendar integration fixture')
assert.match(migrationWorkflow,/20261002100000_official_calendar_sources\.sql/,'source registry migration is included in isolated Supabase CI')
console.log('School calendar workflow checks passed.')
